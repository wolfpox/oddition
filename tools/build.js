#!/usr/bin/env node
/* Bundle index.html, css and js into one self-contained file.
 *
 *   node tools/build.js            -> dist/oddition.html  (open it directly, share it)
 *   node tools/build.js --fragment -> also dist/oddition.fragment.html, the same app
 *                                     without <html>/<head>/<body> for hosts that
 *                                     wrap a page in their own document.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const html = read('index.html');
const css = read('css/style.css');
const scripts = [...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map((m) => m[1]);
const js = scripts.map((src) => '/* ' + src + ' */\n' + read(src)).join('\n');
const safeJs = js.replace(/<\/script/gi, '<\\/script');
const fonts = (html.match(/<link rel="stylesheet" href="https:\/\/fonts[^>]+>/) || [''])[0];
const body = html.split('<!--app:start-->')[1].split('<!--app:end-->')[0].trim();

const stamp = new Date().toISOString().slice(0, 10);
const banner = '<!-- Oddition single-file build ' + stamp + ' (generated by tools/build.js; edit the sources, not this file) -->';

const full = [
  '<!doctype html>',
  '<html lang="en">',
  '<head>',
  '<meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
  '<title>Oddition</title>',
  '<meta name="color-scheme" content="dark light">',
  fonts,
  '<style>\n' + css + '\n</style>',
  '</head>',
  '<body>',
  banner,
  body,
  '<script>\n' + safeJs + '\n</script>',
  '</body>',
  '</html>',
  '',
].join('\n');

fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'oddition.html'), full);
console.log('dist/oddition.html', (full.length / 1024).toFixed(1) + ' KB');

if (process.argv.includes('--fragment')) {
  const extra = process.argv.includes('--platform') ? read(process.argv[process.argv.indexOf('--platform') + 1]) : '';
  const fragment = [
    '<title>Oddition</title>',
    '<meta name="claude:viewport-fit-sides" content="cover">',
    fonts,
    '<style>\n' + css + '\n</style>',
    body,
    extra ? '<script>\n' + extra.replace(/<\/script/gi, '<\\/script') + '\n</script>' : '',
    '<script>\n' + safeJs + '\n</script>',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(root, 'dist', 'oddition.fragment.html'), fragment);
  console.log('dist/oddition.fragment.html', (fragment.length / 1024).toFixed(1) + ' KB');
}
